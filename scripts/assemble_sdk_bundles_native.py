#!/usr/bin/env python3
"""Assemble per-bundle native plugins (Android, iOS, macOS, Windows, Linux, Web).

Operates on `build/sdk_bundles/<bundle_id>/` generated by `assemble_sdk_bundles.py`
without editing any source files under `packages/`.

Key architectural guarantees:
  1. `flutter_realtime_sdk` (core) owns the lightweight `processed_video` native
     frame hub on Android/iOS/macOS and zero third-party vendor RTC/IM SDKs.
  2. Each provider bundle (`sdk_livekit`, `sdk_agora`, `sdk_trtc`, `sdk_artc`,
     `sdk_aws`, `sdk_agora_chat`, `sdk_ivs_chat`) compiles and links ONLY its
     own vendor SDK, referencing `flutter_realtime_sdk` for `processed_video`
     on Android/Apple and resolving `flutter_realtime_sdk_effects_plugin.dll`
     dynamically via `GetModuleHandleW` on Windows.
  3. Vendor quirks (Alibaba Maven, IVS `.xcframework` / stages AAR, Hyphenate
     R8 rules & `libaosl.so` deduplication, ONNX Runtime / DirectML) are strictly
     confined to the single bundle that owns them.
"""

